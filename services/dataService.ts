  private parseRawData() {
    const lines = RAW_DATA_STRING.split('\n');
    const volMap = new Map<string, Volunteer>();
    const txList: Transaction[] = [];

    let lastDateStr = ''; // State to remember the last valid date

    lines.forEach((line, index) => {
        const parts = line.split('|');
        if (parts.length < 3) return;

        let dateStr = parts[0].trim(); // DD/MM/YYYY
        
        // Handle rows with empty dates by using the last valid date found
        if (!dateStr && lastDateStr) {
            dateStr = lastDateStr;
        } else if (dateStr) {
            lastDateStr = dateStr;
        }

        const empId = parts[1].trim();
        const name = parts[2].trim();
        const typeRaw = parts[3]?.trim() || 'HO';
        // Admin status can be in column 4 or 5
        const isAdmin = typeRaw.includes('ADMIN') || parts[4]?.includes('ADMIN');

        // Volunteer Logic: Last record updates info
        const volId = 'v_' + empId;
        volMap.set(volId, {
            id: volId,
            empId: empId,
            name: name,
            type: typeRaw.includes('Branch') || typeRaw.includes('BRANCH') ? 'Branch' : 'HO',
            isStaff: !!isAdmin
        });

        // Transaction Logic
        // Parse Date
        let dateObj: Date;
        if (dateStr) {
             const [day, month, year] = dateStr.split('/').map(Number);
             dateObj = new Date(year, month - 1, day);
        } else {
             // Fallback if absolutely no date is found anywhere
             dateObj = new Date();
        }
        
        // ** SIMPLE THAI YEAR LOGIC (Requested) **
        // Logic: Year + 543 ONLY
        const fy = getFiscalYear(dateObj); 
        
        const points = 20;

        txList.push({
            id: `tx_init_${index}`,
            volunteerId: volId,
            amount: points,
            type: 'ACTIVITY',
            description: 'ร่วมกิจกรรมอาสา',
            date: dateObj.toISOString(),
            thaiYear: fy,
            createdBy: 'System'
        });
    });

    this.volunteers = Array.from(volMap.values());
    this.transactions = txList;
    this.save();
  }

